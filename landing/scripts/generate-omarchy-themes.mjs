// Regenerates app/content/omarchyThemes.ts from the repo's Omarchy fixtures
// (testing/fixtures/omarchy/themes, copied verbatim from basecamp/omarchy).
// Run from landing/: node scripts/generate-omarchy-themes.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../../testing/fixtures/omarchy/themes/", import.meta.url);
const label = name => name.split("-").map(part => part[0].toUpperCase() + part.slice(1)).join(" ");

const themes = readdirSync(dir)
  .filter(file => file.endsWith(".toml"))
  .sort()
  .map(file => {
    const name = file.replace(/\.toml$/, "");
    const colors = {};
    let mode = "dark";
    for (const line of readFileSync(new URL(file, dir), "utf8").split("\n")) {
      const match = line.match(/^\s*([a-z_]+)\s*=\s*"([^"]*)"/);
      if (!match) continue;
      if (match[1] === "mode") mode = match[2] === "light" ? "light" : "dark";
      else if (/^#[0-9a-f]{3,8}$/i.test(match[2])) colors[match[1]] = match[2].toLowerCase();
    }
    return { name, label: label(name), mode, colors };
  });

const body = `// Generated by scripts/generate-omarchy-themes.mjs from testing/fixtures/omarchy/themes.
// Do not edit by hand; landing/test/omarchy.test.ts fails if this drifts from the fixtures.
import type { OmarchyMode } from "../lib/omarchyTheme";

export type OmarchySiteTheme = { name: string; label: string; mode: OmarchyMode; colors: Record<string, string> };

/** Omarchy's install default. */
export const DEFAULT_OMARCHY_THEME = "tokyo-night";

export const OMARCHY_THEMES: OmarchySiteTheme[] = ${JSON.stringify(themes, null, 2)};
`;
writeFileSync(new URL("../app/content/omarchyThemes.ts", import.meta.url), body);
console.log(`wrote ${themes.length} themes`);
